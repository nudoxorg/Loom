// codexProjectCommand returns a git-toplevel-relative command string for
// a project-scoped Codex hook. Codex has no ${CLAUDE_PROJECT_DIR}-style
// path placeholder; its own docs recommend embedding
// $(git rev-parse --show-toplevel) directly in the command string
// instead, since Codex may be started from a subdirectory.
func codexProjectCommand(scriptName string) string {
	return `"$(git rev-parse --show-toplevel)/.codex/hooks/` + scriptName + `"`
}

func writeScriptIfChanged(path, content string) (bool, error) {
	existing, err := os.ReadFile(path)
	if err == nil && string(existing) == content {
		return false, nil
	}
	if err != nil && !os.IsNotExist(err) {
		return false, fmt.Errorf("reading %s: %w", path, err)
	}

	if err := os.WriteFile(path, []byte(content), 0o755); err != nil {
		return false, fmt.Errorf("writing %s: %w", path, err)
	}

	return true, nil
}

// hookWiring is one (event, matcher, command) entry to ensure exists in a
// hooks config file. matcher is left empty for events like SessionStart
// that don't match against a tool name.
type hookWiring struct {
	event   string
	matcher string
	command string
}

// mergeSettingsFile ensures each of wirings exists somewhere under its
// event in settingsPath's "hooks" block, merging into whatever's already
// there — every other top-level key, and every hook entry Loom didn't
// itself add, survives untouched. Shared by both the Claude
// (settings.json, mixed in with unrelated config) and Codex (a dedicated
// hooks.json) targets; nothing here assumes which one it's writing.
func mergeSettingsFile(settingsPath string, wirings []hookWiring) (bool, error) {
	raw := map[string]json.RawMessage{}
	data, err := os.ReadFile(settingsPath)
	switch {
	case err == nil:
		if err := json.Unmarshal(data, &raw); err != nil {
			return false, fmt.Errorf("parsing %s: %w", settingsPath, err)
		}
	case os.IsNotExist(err):
		if err := os.MkdirAll(filepath.Dir(settingsPath), 0o755); err != nil {
			return false, fmt.Errorf("creating hooks config dir: %w", err)
		}
	default:
		return false, fmt.Errorf("reading %s: %w", settingsPath, err)
	}

	hooksByEvent := map[string][]hookMatcher{}
	if existing, ok := raw["hooks"]; ok {
		if err := json.Unmarshal(existing, &hooksByEvent); err != nil {
			return false, fmt.Errorf("parsing hooks in %s: %w", settingsPath, err)
		}
	}

	changed := false
	for _, w := range wirings {
		changed = addHookIfMissing(hooksByEvent, w.event, w.matcher, w.command) || changed
	}

	if !changed {
		return false, nil
	}

	hooksJSON, err := json.Marshal(hooksByEvent)
	if err != nil {
		return false, fmt.Errorf("encoding hooks: %w", err)
	}
	raw["hooks"] = hooksJSON

	out, err := json.MarshalIndent(raw, "", "  ")
	if err != nil {
		return false, fmt.Errorf("encoding %s: %w", settingsPath, err)
	}

	if err := os.WriteFile(settingsPath, out, 0o644); err != nil {
		return false, fmt.Errorf("writing %s: %w", settingsPath, err)
	}

	return true, nil
}

// addHookIfMissing appends a new matcher group running command under
// event, unless some existing group under that event already runs it —
// which is what makes Install idempotent.
func addHookIfMissing(hooksByEvent map[string][]hookMatcher, event, matcher, command string) bool {
	for _, group := range hooksByEvent[event] {
		for _, h := range group.Hooks {
			if h.Command == command {
				return false
			}
		}
	}

	hooksByEvent[event] = append(hooksByEvent[event], hookMatcher{
		Matcher: matcher,
		Hooks:   []hookEntry{{Type: "command", Command: command}},
	})

	return true
}
